    static let questionsPerQuiz = 10

    /// Builds a fresh, shuffled quiz for the given topic.
    /// - Picks `questionsPerQuiz` random questions from the pool (safe even as pools grow to 20-30+).
    /// - Shuffles each question's option order too, so the correct answer isn't always in the same spot.
    static func buildQuiz(for topic: String) -> [GrammarMCQQuestion] {
        guard let pool = pools[topic], !pool.isEmpty else { return [] }
        let count = min(questionsPerQuiz, pool.count)
        let picked = Array(pool.shuffled().prefix(count))
        return picked.map { q in
            GrammarMCQQuestion(question: q.question, options: q.options.shuffled(), correctAnswer: q.correctAnswer)
        }
    }
